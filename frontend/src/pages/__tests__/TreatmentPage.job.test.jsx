import React, { act } from "react";
import { createRoot } from "react-dom/client";
import axios from "axios";
import { toast } from "sonner";
import TreatmentPage from "../TreatmentPage";
import { addDraft, readDrafts, updateDrafts } from "../../lib/treatmentDrafts";
jest.mock("axios", () => ({ get: jest.fn(), post: jest.fn() }));
jest.mock("sonner", () => ({ toast: { error: jest.fn(), warning: jest.fn(), success: jest.fn() } }));
jest.mock("react-router-dom", () => ({ useNavigate: () => jest.fn() }));
let mockRole = "crew";
jest.mock("../../context/AuthContext", () => ({ API: "/api", useAuth: () => ({ user: { user_id: "crew", email: "crew@example.invalid", role: mockRole } }) }));
jest.mock("../../context/ActiveJobContext", () => ({ useActiveJobSelection: () => ({ jobId: "job-1", rig: "rig-1", runNumber: 1, well: { name: "Well A" } }) }));
jest.mock("../../context/RigContext", () => ({ rigLabel: () => "Rig 1" }));
jest.mock("../../context/OperatorTelemetryContext", () => ({ useOperatorTelemetry: () => ({ telemetry: null }) }));
jest.mock("../../hooks/usePullToRefresh", () => ({ usePullToRefresh: () => ({ ref: null, progress: 0, refreshing: false }), PullIndicator: () => null }));
jest.mock("../../components/LiveStripSidebar", () => () => null);
jest.mock("../../lib/fieldStore", () => ({ getStateSync: () => null, setState: jest.fn() }));
jest.mock("../../lib/treatmentDrafts", () => ({ draftKey: () => "drafts", readDrafts: jest.fn(), addDraft: jest.fn(), updateDrafts: jest.fn() }));
global.IS_REACT_ACT_ENVIRONMENT = true;
let root, host;
const treatment = { treatment_id: "t-1", name: "Well A / Run 1", created_at: "2026-01-01T12:00:00Z" };
beforeEach(() => {
  mockRole = "crew";
  Object.defineProperty(navigator, "onLine", { configurable: true, value: true });
  readDrafts.mockReturnValue([]);
  axios.get.mockImplementation((url) => Promise.resolve({ data: url.endsWith("/active") ? { treatment: null } : { entries: [] } }));
  host = document.createElement("div");
  root = createRoot(host);
});
afterEach(async () => { await act(async () => root.unmount()); });
test("quick operational events do not require the selected NPT duration and save offline", async () => {
  Object.defineProperty(navigator, "onLine", { configurable: true, value: false });
  addDraft.mockImplementation(async (_key, body) => ({ ...body, entry_id: "draft-1", sync_status: "local" }));
  await act(async () => root.render(<TreatmentPage />));
  await act(async () => host.querySelector('[data-testid="treatment-kind-npt"]').click());
  await act(async () => [...host.querySelectorAll("button")].find((button) => button.textContent === "RIH in Hole").click());
  expect(addDraft).toHaveBeenCalledWith("drafts", expect.objectContaining({ kind: "event", operation_code: 12, event_at: expect.any(String) }), expect.objectContaining({ rig_id: "rig-1" }));
  expect(axios.post).not.toHaveBeenCalled();
  expect(toast.error).not.toHaveBeenCalled();
});
test("guest log access never exposes creation, close, upload or composer controls", async () => {
  mockRole = "guest";
  axios.get.mockImplementation((url) => Promise.resolve({ data: url.endsWith("/active") ? { treatment } : { entries: [] } }));
  await act(async () => root.render(<TreatmentPage />));
  expect(host.querySelector('[data-testid="treatment-close"]')).toBeNull();
  expect(host.querySelector('[data-testid="treatment-composer"]')).toBeNull();
  expect(host.querySelector('[data-testid="treatment-start"]')).toBeNull();
});
test("confirmed upload with failed device cleanup is explicitly non-retryable", async () => {
  const draft = { entry_id: "d-1", rig_id: "rig-1", treatment_id: "t-1", text: "Fixture note", event_at: treatment.created_at, sync_status: "local" };
  readDrafts.mockReturnValue([draft]);
  axios.get.mockImplementation((url) => Promise.resolve({ data: url.endsWith("/active") ? { treatment } : { entries: [] } }));
  axios.post.mockResolvedValue({ data: { ...draft, entry_id: "server-1", created_at: treatment.created_at } });
  updateDrafts.mockResolvedValueOnce([{ ...draft, sync_status: "uncertain" }]).mockRejectedValueOnce(new Error("Storage failed"));
  const confirm = jest.spyOn(window, "confirm").mockReturnValue(true);
  await act(async () => root.render(<TreatmentPage />));
  await act(async () => [...host.querySelectorAll("button")].find((button) => button.textContent.startsWith("Review / upload")).click());
  expect(toast.error).toHaveBeenCalledWith(expect.stringMatching(/Server confirmed entry server-1.*Do not upload again/));
  expect([...host.querySelectorAll("button")].find((button) => button.textContent.startsWith("Review / upload")).disabled).toBe(true);
  expect(axios.post).toHaveBeenCalledTimes(1);
  confirm.mockRestore();
});
